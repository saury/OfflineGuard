#!/usr/bin/env python3
"""Generate a build-version header, touching it only when its content changes."""

import json
import os
from pathlib import Path
import re
import sys


def main():
    version = os.environ.get("VERSION", "dev")
    number = r"(?:0|[1-9][0-9]*)"
    if not re.fullmatch(rf"(?:{number}\.{number}\.{number}|dev(?:-[0-9a-f]{{7,40}})?)", version):
        sys.exit("VERSION must be MAJOR.MINOR.PATCH, dev, or dev-<commit SHA>.")
    if len(sys.argv) != 2:
        sys.exit("Usage: write-version-header.py <output path>")
    path = Path(sys.argv[1])
    content = "// Generated by scripts/write-version-header.py.\n#pragma once\n"
    content += f"#define OG_VERSION {json.dumps(version)}\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != content:
        path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
